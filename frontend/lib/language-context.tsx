export type TranslationKey = keyof typeof dict.en
type LanguageContextValue = { lang: Language; setLang: (lang: Language) => void; t: (key: TranslationKey) => string }
const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Language>('en')
  useEffect(() => {
    Object.keys(dict.en).forEach((key) => {
      if (!(key in dict.bn)) console.warn(`[language] Missing Bangla translation: ${key}`)
    })
    document.documentElement.lang = lang
  }, [lang])
  const value = useMemo(() => ({ lang, setLang, t: (key: TranslationKey) => dict[lang][key] }), [lang])
  return <LanguageContext.Provider value={value}><div className={lang === 'bn' ? 'lang-bn' : ''}>{children}</div></LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within LanguageProvider')
  return context
}
